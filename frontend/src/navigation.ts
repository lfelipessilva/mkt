import type { NavTab } from "./types";

export const NAV_TABS: readonly NavTab[] = [
  "desempenho",
  "galeria",
  "contas",
  "textos",
  "midias",
  "integracoes",
];

/** Canonical URL path for each tab. */
export const TAB_PATHS: Record<NavTab, string> = {
  desempenho: "/desempenho",
  galeria: "/galeria",
  contas: "/contas",
  textos: "/textos",
  midias: "/midias",
  integracoes: "/integracoes",
};

export const DEFAULT_TAB: NavTab = "desempenho";

const PATH_TO_TAB = new Map<string, NavTab>(
  NAV_TABS.map((tab) => [TAB_PATHS[tab], tab])
);

/** Removes duplicate/trailing slashes so `/galeria/` and `/galeria` match. */
export function normalizePathname(pathname: string): string {
  if (!pathname) return "/";
  let normalized = pathname.trim();
  if (!normalized.startsWith("/")) normalized = `/${normalized}`;
  normalized = normalized.replace(/\/{2,}/g, "/").replace(/\/+$/, "");
  return normalized === "" ? "/" : normalized.toLowerCase();
}

/** Resolves a tab from the URL pathname, or `undefined` when the path is unknown. */
export function parsePathTab(pathname: string): NavTab | undefined {
  return PATH_TO_TAB.get(normalizePathname(pathname));
}

/**
 * Parses legacy query deep links (`?tab=galeria&run=<id>`).
 * Notifications generated by the backend still use this format.
 */
export function parseDeepLinkParams(search: string): { tab?: NavTab; runId?: string } {
  if (!search) return {};
  const query = search.startsWith("?") ? search.slice(1) : search;
  if (!query) return {};

  const params = new URLSearchParams(query);
  const rawTab = params.get("tab");
  const rawRun = params.get("run") || params.get("runId");

  const result: { tab?: NavTab; runId?: string } = {};

  if (rawTab && (NAV_TABS as readonly string[]).includes(rawTab)) {
    result.tab = rawTab as NavTab;
  }
  if (rawRun && rawRun.trim().length > 0) {
    result.runId = rawRun.trim();
  }

  return result;
}

export interface ResolvedLocation {
  tab: NavTab;
  runId?: string;
  /** Canonical path+query for the resolved location. */
  url: string;
}

/**
 * Resolves the current location. The path wins over the legacy `?tab=` query,
 * so `/galeria?tab=textos` renders the gallery. Unknown paths fall back to the
 * legacy tab query and finally to the default tab.
 */
export function resolveLocation(pathname: string, search: string): ResolvedLocation {
  const query = parseDeepLinkParams(search);
  const tab = parsePathTab(pathname) ?? query.tab ?? DEFAULT_TAB;
  const runId = tab === "galeria" ? query.runId : undefined;

  return { tab, runId, url: buildTabUrl(tab, runId) };
}

/** Builds the canonical URL for a tab, keeping the focused run on the gallery. */
export function buildTabUrl(tab: NavTab, runId?: string): string {
  const path = TAB_PATHS[tab];
  const trimmedRun = runId?.trim();
  if (tab === "galeria" && trimmedRun) {
    return `${path}?run=${encodeURIComponent(trimmedRun)}`;
  }
  return path;
}
